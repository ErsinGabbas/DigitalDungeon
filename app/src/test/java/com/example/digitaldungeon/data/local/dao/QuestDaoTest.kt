package com.example.digitaldungeon.data.local.dao

import android.database.sqlite.SQLiteConstraintException
import androidx.room.Room
import androidx.test.ext.junit.runners.AndroidJUnit4
import androidx.test.platform.app.InstrumentationRegistry
import com.example.digitaldungeon.data.local.database.AppDatabase
import com.example.digitaldungeon.data.local.entity.CampaignEntity
import com.example.digitaldungeon.data.local.entity.QuestEntity
import com.example.digitaldungeon.domain.model.QuestCategory
import com.example.digitaldungeon.domain.model.QuestPriority
import com.example.digitaldungeon.domain.model.QuestStatus
import kotlinx.coroutines.flow.first
import kotlinx.coroutines.runBlocking
import org.junit.After
import org.junit.Assert.assertEquals
import org.junit.Assert.assertNull
import org.junit.Assert.assertThrows
import org.junit.Assert.assertTrue
import org.junit.Before
import org.junit.Test
import org.junit.runner.RunWith

/**
 * [QuestDao] against a real Room instance.
 *
 * The three things only a real database can answer are asserted here: that a quest cannot exist
 * without its campaign, that deleting a campaign takes its quests with it, and that a query scoped
 * to one campaign never returns another's. None of that is reachable from a JVM unit test, where
 * the repository is a fake and the foreign keys do not exist.
 */
@RunWith(AndroidJUnit4::class)
class QuestDaoTest {

    private lateinit var database: AppDatabase
    private lateinit var dao: QuestDao

    @Before
    fun setUp() {
        val context = InstrumentationRegistry.getInstrumentation().targetContext

        // In-memory, so the test can never disturb the installed app's real journal.
        database = Room.inMemoryDatabaseBuilder(context, AppDatabase::class.java)
            .build()
        dao = database.questDao()

        runBlocking {
            database.campaignDao().insertCampaigns(
                listOf(
                    CampaignEntity(
                        id = CAMPAIGN_A,
                        name = "Curse of Strahd",
                        description = "Barovia",
                        createdAt = 1L
                    ),
                    CampaignEntity(
                        id = CAMPAIGN_B,
                        name = "Tomb of Annihilation",
                        description = "",
                        createdAt = 2L
                    )
                )
            )
        }
    }

    @After
    fun tearDown() {
        database.close()
    }

    // ------------------------------------------------------------- writing

    @Test
    fun insertQuest_withNothingButATitle_isStoredWithTheDefaultsItWasGiven() = runBlocking {
        // What "a quest is one line of text" looks like by the time it reaches the database: the
        // entity's own defaults for the id and the in-world date, and whatever the repository
        // passed for the rest.
        dao.insertQuest(
            QuestEntity(
                campaignId = CAMPAIGN_A,
                title = "The miller's missing daughter",
                description = "",
                category = QuestCategory.SIDE,
                status = QuestStatus.NOT_STARTED,
                priority = QuestPriority.NORMAL,
                isHidden = false,
                createdAt = 10L
            )
        )

        val stored = dao.getQuestsForCampaign(CAMPAIGN_A).first().single()
        assertEquals("The miller's missing daughter", stored.title)
        assertEquals("", stored.description)
        assertEquals(QuestCategory.SIDE, stored.category)
        assertEquals(QuestStatus.NOT_STARTED, stored.status)
        assertEquals(QuestPriority.NORMAL, stored.priority)
        assertEquals(false, stored.isHidden)
        assertNull(stored.inGameDate)
        // An autogenerated key, so the row is addressable even though the caller named no id.
        assertTrue(stored.id > 0)
    }

    @Test
    fun insertQuest_keepsEveryFieldItWasGiven() = runBlocking {
        dao.insertQuest(
            quest(
                id = 1,
                title = "Strahd's invitation",
                description = "Dinner at Ravenloft",
                category = QuestCategory.MAIN,
                status = QuestStatus.PAUSED,
                priority = QuestPriority.HIGH,
                isHidden = true,
                inGameDate = "14th of Neth, 735 BC"
            )
        )

        assertEquals(
            quest(
                id = 1,
                title = "Strahd's invitation",
                description = "Dinner at Ravenloft",
                category = QuestCategory.MAIN,
                status = QuestStatus.PAUSED,
                priority = QuestPriority.HIGH,
                isHidden = true,
                inGameDate = "14th of Neth, 735 BC"
            ),
            dao.getQuestsForCampaign(CAMPAIGN_A).first().single()
        )
    }

    @Test
    fun severalQuestsInOneCampaign_allSurviveAndComeBackNewestFirst() = runBlocking {
        dao.insertQuests(
            listOf(
                quest(id = 1, title = "First", createdAt = 10L),
                quest(id = 2, title = "Second", createdAt = 20L),
                quest(id = 3, title = "Third", createdAt = 30L)
            )
        )

        val stored = dao.getQuestsForCampaign(CAMPAIGN_A).first()

        // The order the list screen then sorts further; what the query owes is that it is stable.
        assertEquals(listOf("Third", "Second", "First"), stored.map { it.title })
    }

    @Test
    fun insertQuest_forACampaignThatDoesNotExist_isRefused() = runBlocking {
        // The foreign key is what makes "every quest belongs to a campaign" a property of the
        // schema rather than of the code that writes to it.
        assertThrows(SQLiteConstraintException::class.java) {
            runBlocking {
                dao.insertQuest(quest(id = 1, campaignId = 999))
            }
        }
        Unit
    }

    // ----------------------------------------------------------- isolation

    @Test
    fun getQuestsForCampaign_neverReturnsAnotherCampaignsQuests() = runBlocking {
        dao.insertQuests(
            listOf(
                quest(id = 1, campaignId = CAMPAIGN_A, title = "Barovia A"),
                quest(id = 2, campaignId = CAMPAIGN_A, title = "Barovia B"),
                quest(id = 3, campaignId = CAMPAIGN_B, title = "Chult A")
            )
        )

        assertEquals(
            listOf("Barovia B", "Barovia A"),
            dao.getQuestsForCampaign(CAMPAIGN_A).first().map { it.title }
        )
        assertEquals(
            listOf("Chult A"),
            dao.getQuestsForCampaign(CAMPAIGN_B).first().map { it.title }
        )
    }

    @Test
    fun getQuestsForCampaign_forACampaignWithoutQuests_isEmptyAndNotAFailure() = runBlocking {
        dao.insertQuest(quest(id = 1, campaignId = CAMPAIGN_A))

        assertTrue(dao.getQuestsForCampaign(CAMPAIGN_B).first().isEmpty())
    }

    // ------------------------------------------------------------ reading

    @Test
    fun getQuestById_returnsTheOneRowAndNullForAnythingElse() = runBlocking {
        dao.insertQuest(quest(id = 1, title = "Escort Ireena"))

        assertEquals("Escort Ireena", dao.getQuestById(1).first()?.title)
        assertNull(dao.getQuestById(2).first())
    }

    @Test
    fun getAllQuests_isOrderedForAStableBackupDocument() = runBlocking {
        dao.insertQuests(
            listOf(
                quest(id = 3, campaignId = CAMPAIGN_B),
                quest(id = 1, campaignId = CAMPAIGN_A),
                quest(id = 2, campaignId = CAMPAIGN_A)
            )
        )

        assertEquals(listOf(1, 2, 3), dao.getAllQuests().map { it.id })
    }

    // ------------------------------------------------------------ updating

    @Test
    fun updateQuest_rewritesTheEditableFieldsAndKeepsTheRest() = runBlocking {
        dao.insertQuest(quest(id = 1, title = "Escort Ireena", createdAt = 10L))

        dao.updateQuest(
            id = 1,
            title = "Escort Ireena to Vallaki",
            description = "past the Tser Pool",
            category = QuestCategory.MAIN,
            status = QuestStatus.ACTIVE,
            priority = QuestPriority.HIGH,
            isHidden = true,
            inGameDate = "14th of Neth"
        )

        val stored = dao.getQuestById(1).first()!!
        assertEquals("Escort Ireena to Vallaki", stored.title)
        assertEquals("past the Tser Pool", stored.description)
        assertEquals(QuestCategory.MAIN, stored.category)
        assertEquals(QuestStatus.ACTIVE, stored.status)
        assertEquals(QuestPriority.HIGH, stored.priority)
        assertEquals(true, stored.isHidden)
        assertEquals("14th of Neth", stored.inGameDate)
        // Neither of these is editable: when a quest was written down is a fact, and the campaign
        // it belongs to is the boundary that keeps two campaigns apart.
        assertEquals(10L, stored.createdAt)
        assertEquals(CAMPAIGN_A, stored.campaignId)
    }

    @Test
    fun updateQuest_canClearTheInGameDate() = runBlocking {
        dao.insertQuest(quest(id = 1, inGameDate = "14th of Neth"))

        dao.updateQuest(
            id = 1,
            title = "Escort Ireena",
            description = "",
            category = QuestCategory.SIDE,
            status = QuestStatus.NOT_STARTED,
            priority = QuestPriority.NORMAL,
            isHidden = false,
            inGameDate = null
        )

        assertNull(dao.getQuestById(1).first()?.inGameDate)
    }

    @Test
    fun updateQuestStatus_touchesNothingButTheStatus() = runBlocking {
        dao.insertQuest(
            quest(
                id = 1,
                title = "Escort Ireena",
                description = "past the Tser Pool",
                category = QuestCategory.MAIN,
                status = QuestStatus.NOT_STARTED,
                priority = QuestPriority.HIGH,
                isHidden = true,
                inGameDate = "14th of Neth"
            )
        )

        dao.updateQuestStatus(1, QuestStatus.ACTIVE)

        assertEquals(
            quest(
                id = 1,
                title = "Escort Ireena",
                description = "past the Tser Pool",
                category = QuestCategory.MAIN,
                status = QuestStatus.ACTIVE,
                priority = QuestPriority.HIGH,
                isHidden = true,
                inGameDate = "14th of Neth"
            ),
            dao.getQuestById(1).first()
        )
    }

    @Test
    fun updateQuestStatus_reopensAFinishedQuest() = runBlocking {
        dao.insertQuest(quest(id = 1, status = QuestStatus.NOT_STARTED))

        // Nothing is terminal, in either direction: the database does not police the transition
        // because the story does not either.
        dao.updateQuestStatus(1, QuestStatus.COMPLETED)
        assertEquals(QuestStatus.COMPLETED, dao.getQuestById(1).first()?.status)

        dao.updateQuestStatus(1, QuestStatus.ACTIVE)
        assertEquals(QuestStatus.ACTIVE, dao.getQuestById(1).first()?.status)

        dao.updateQuestStatus(1, QuestStatus.FAILED)
        assertEquals(QuestStatus.FAILED, dao.getQuestById(1).first()?.status)

        dao.updateQuestStatus(1, QuestStatus.PAUSED)
        assertEquals(QuestStatus.PAUSED, dao.getQuestById(1).first()?.status)
    }

    // ------------------------------------------------------------ deleting

    @Test
    fun deleteQuest_removesOnlyThatQuest() = runBlocking {
        dao.insertQuests(
            listOf(
                quest(id = 1, title = "Kept"),
                quest(id = 2, title = "Deleted")
            )
        )

        dao.deleteQuest(2)

        assertEquals(
            listOf("Kept"),
            dao.getQuestsForCampaign(CAMPAIGN_A).first().map { it.title }
        )
    }

    @Test
    fun deletingACampaign_takesItsQuestsWithIt_andLeavesTheOtherCampaignAlone() = runBlocking {
        dao.insertQuests(
            listOf(
                quest(id = 1, campaignId = CAMPAIGN_A),
                quest(id = 2, campaignId = CAMPAIGN_A),
                quest(id = 3, campaignId = CAMPAIGN_B)
            )
        )

        database.campaignDao().deleteCampaign(CAMPAIGN_A)

        // ON DELETE CASCADE, so a deleted campaign cannot leave its quests behind as rows nothing
        // points at.
        assertTrue(dao.getQuestsForCampaign(CAMPAIGN_A).first().isEmpty())
        assertEquals(listOf(3), dao.getQuestsForCampaign(CAMPAIGN_B).first().map { it.id })
    }

    @Test
    fun deleteAllQuests_emptiesTheTableAcrossEveryCampaign() = runBlocking {
        dao.insertQuests(
            listOf(
                quest(id = 1, campaignId = CAMPAIGN_A),
                quest(id = 2, campaignId = CAMPAIGN_B)
            )
        )

        dao.deleteAllQuests()

        assertTrue(dao.getAllQuests().isEmpty())
        // The campaigns themselves are untouched - this is the restore path, not a cascade.
        assertEquals(2, database.campaignDao().getAllCampaigns().size)
    }

    // ------------------------------------------------------------- helpers

    private fun quest(
        id: Int = 0,
        campaignId: Int = CAMPAIGN_A,
        title: String = "Quest $id",
        description: String = "description of quest $id",
        category: QuestCategory = QuestCategory.SIDE,
        status: QuestStatus = QuestStatus.NOT_STARTED,
        priority: QuestPriority = QuestPriority.NORMAL,
        isHidden: Boolean = false,
        createdAt: Long = id * 10L,
        inGameDate: String? = null
    ) = QuestEntity(
        id = id,
        campaignId = campaignId,
        title = title,
        description = description,
        category = category,
        status = status,
        priority = priority,
        isHidden = isHidden,
        createdAt = createdAt,
        inGameDate = inGameDate
    )

    private companion object {
        const val CAMPAIGN_A = 1
        const val CAMPAIGN_B = 2
    }
}
