    @Test
    fun addRelation_relatedBothWaysRound_isAddedThenAlreadyExistsWithOneRow() = runTest {

        val campaignId = env.campaign()
        val oneWay = env.quest(campaignId, "Recover the Tarokka Deck")
        val otherWay = env.quest(campaignId, "Read the Cards for Ireena")

        assertEquals(
            AddRelationResult.Added,
            env.relations.addRelation(oneWay, otherWay, QuestRelationType.RELATED)
        )
        assertEquals(
            AddRelationResult.AlreadyExists,
            env.relations.addRelation(otherWay, oneWay, QuestRelationType.RELATED)
        )

        // `RELATED` is normalised by the same rule as `ALTERNATIVE` and is asserted separately,
        // because the two share a branch in the implementation and a narrowing of that branch to
        // one type would otherwise go unnoticed.
        assertEquals(
            listOf(Triple(oneWay, otherWay, QuestRelationType.RELATED)),
            storedRelations()
        )
    }

    @Test
    fun addRelation_parentChildTheOtherWayRound_isNotADuplicateButADifferentFact() = runTest {

        val campaignId = env.campaign()
        val arc = env.quest(campaignId, "The Dinner Invitation")
        val errand = env.quest(campaignId, "Find the Missing Coachman")

        assertEquals(
            AddRelationResult.Added,
            env.relations.addRelation(arc, errand, QuestRelationType.PARENT_CHILD)
        )

        // Not `AlreadyExists`: the directional types are *not* normalised by id, so swapping the
        // ends states something genuinely different. It is refused, but as a cycle rather than as
        // a duplicate, and the user gets told the right thing. This assertion is what pins the
        // boundary between the two normalisation rules.
        assertEquals(
            AddRelationResult.WouldCreateCycle,
            env.relations.addRelation(errand, arc, QuestRelationType.PARENT_CHILD)
        )

        assertEquals(
            listOf(Triple(arc, errand, QuestRelationType.PARENT_CHILD)),
            storedRelations()
        )
    }

    // -------------------------------------------------------------- cycles

    @Test
    fun addRelation_closingAParentChainOfThree_isRefusedAndWritesNothing() = runTest {

        val campaignId = env.campaign()
        val grandparent = env.quest(campaignId, "Escape Barovia")
        val parent = env.quest(campaignId, "Destroy Strahd")
        val child = env.quest(campaignId, "Recover the Sunsword")

        env.relations.addRelation(grandparent, parent, QuestRelationType.PARENT_CHILD)
        env.relations.addRelation(parent, child, QuestRelationType.PARENT_CHILD)

        val before = storedRelations()

        assertEquals(
            AddRelationResult.WouldCreateCycle,
            env.relations.addRelation(child, grandparent, QuestRelationType.PARENT_CHILD)
        )

        // The whole check-then-write sits in one transaction, so a refusal has to leave the table
        // byte for byte as it was. Compared against a snapshot rather than a literal list, because
        // what matters is that nothing moved, not what was there.
        assertEquals(before, storedRelations())
        assertEquals(2, storedRelations().size)
    }

    @Test
    fun addRelation_makingAChildTheParentOfItsOwnParent_isRefusedAndWritesNothing() = runTest {

        val campaignId = env.campaign()
        val parent = env.quest(campaignId, "Destroy Strahd")
        val child = env.quest(campaignId, "Recover the Sunsword")

        env.relations.addRelation(parent, child, QuestRelationType.PARENT_CHILD)

        // The shortest loop there is, and the one a DM is most likely to reach for by accident.
        // It falls out of the same upward walk as the longer chains rather than being special-cased.
        assertEquals(
            AddRelationResult.WouldCreateCycle,
            env.relations.addRelation(child, parent, QuestRelationType.PARENT_CHILD)
        )

        assertEquals(
            listOf(Triple(parent, child, QuestRelationType.PARENT_CHILD)),
            storedRelations()
        )
    }

    @Test
    fun addRelation_closingACycleThroughTheSecondOfTwoParents_isRefusedAndWritesNothing() =
        runTest {

            val campaignId = env.campaign()

            // Created in this order so the ids ascend the way the expected rows below assume.
            val sideQuest = env.quest(campaignId, "Buy Silvered Weapons in Vallaki")
            val firstArc = env.quest(campaignId, "The Dinner Invitation")
            val secondArc = env.quest(campaignId, "The Hunt for Van Richten")
            val firstArcParent = env.quest(campaignId, "Escape Barovia")
            val secondArcParent = env.quest(campaignId, "Destroy Strahd")

            // `sideQuest` has two parents, and each of those has a parent of its own. The loop
            // being attempted runs up the *second* branch only.
            env.relations.addRelation(firstArc, sideQuest, QuestRelationType.PARENT_CHILD)
            env.relations.addRelation(secondArc, sideQuest, QuestRelationType.PARENT_CHILD)
            env.relations.addRelation(firstArcParent, firstArc, QuestRelationType.PARENT_CHILD)
            env.relations.addRelation(secondArcParent, secondArc, QuestRelationType.PARENT_CHILD)

            val before = storedRelations()
            assertEquals(4, before.size)

            // A walk that followed only the first parent it found would exhaust the `firstArc`
            // branch, never reach `secondArcParent`, and store a loop. Breadth-first over the whole
            // ancestry is the only thing that catches this, which is why the two-parent shape is
            // set up at all.
            assertEquals(
                AddRelationResult.WouldCreateCycle,
                env.relations.addRelation(sideQuest, secondArcParent, QuestRelationType.PARENT_CHILD)
            )

            assertEquals(before, storedRelations())
        }

    @Test
    fun addRelation_aPrecedesLoop_isAllowed_whichIsAKnownLimitation() = runTest {

        val campaignId = env.campaign()
        val oneStep = env.quest(campaignId, "Find the Missing Coachman")
        val otherStep = env.quest(campaignId, "Escort the Wagon to Vallaki")

        assertEquals(
            AddRelationResult.Added,
            env.relations.addRelation(oneStep, otherStep, QuestRelationType.PRECEDES)
        )

        // Plainly: this is a known limitation of the current implementation and not something this
        // test endorses. The cycle check is gated on `PARENT_CHILD`, so "A precedes B" and "B
        // precedes A" are both accepted and the journal is left holding an impossible ordering.
        // The reasoning on the implementation is that an ordering loop is contradictory rather than
        // structurally circular - it cannot make a quest its own ancestor and so cannot hang a
        // tree walk - but a DM reading those two rows still learns nothing. Asserted as it is so
        // that the day the check is widened, this test fails and has to be rewritten deliberately
        // rather than the behaviour changing unobserved.
        assertEquals(
            AddRelationResult.Added,
            env.relations.addRelation(otherStep, oneStep, QuestRelationType.PRECEDES)
        )

        assertEquals(
            listOf(
                Triple(oneStep, otherStep, QuestRelationType.PRECEDES),
                Triple(otherStep, oneStep, QuestRelationType.PRECEDES)
            ),
            storedRelations()
        )
    }

    // ------------------------------------------------- the other refusals

    @Test
    fun addRelation_bothEndsTheSameQuest_isSameQuestAndWritesNothing() = runTest {

        val campaignId = env.campaign()
        val quest = env.quest(campaignId, "Recover the Sunsword")

        // Answered before a transaction is even opened, so this also covers the case of a quest
        // that does not exist being linked to itself: `SameQuest` wins over `QuestMissing`.
        assertEquals(
            AddRelationResult.SameQuest,
            env.relations.addRelation(quest, quest, QuestRelationType.PARENT_CHILD)
        )
        assertEquals(
            AddRelationResult.SameQuest,
            env.relations.addRelation(quest, quest, QuestRelationType.RELATED)
        )

        assertEquals(noRelations, storedRelations())
    }

    @Test
    fun addRelation_aTargetQuestThatDoesNotExist_isQuestMissingAndWritesNothing() = runTest {

        val campaignId = env.campaign()
        val quest = env.quest(campaignId, "Recover the Sunsword")
        val deletedWhileThePickerWasOpen = quest + 1_000

        assertEquals(
            AddRelationResult.QuestMissing,
            env.relations.addRelation(
                quest,
                deletedWhileThePickerWasOpen,
                QuestRelationType.PARENT_CHILD
            )
        )

        // Reported as an outcome rather than left to the foreign key, which would have thrown. The
        // empty table is what proves the check ran before the insert and not instead of it.
        assertEquals(noRelations, storedRelations())
    }

    @Test
    fun addRelation_aSourceQuestThatDoesNotExist_isQuestMissingAndWritesNothing() = runTest {

        val campaignId = env.campaign()
        val quest = env.quest(campaignId, "Recover the Sunsword")
        val deletedWhileThePickerWasOpen = quest + 1_000

        // Both ends are looked up, so it does not matter which of the two went missing. Asserted
        // separately because a check that only read one column would still pass the test above.
        assertEquals(
            AddRelationResult.QuestMissing,
            env.relations.addRelation(
                deletedWhileThePickerWasOpen,
                quest,
                QuestRelationType.PARENT_CHILD
            )
        )

        assertEquals(noRelations, storedRelations())
    }

    @Test
    fun addRelation_theExactSameLinkTwice_isAlreadyExistsAndLeavesOneRow() = runTest {

        val campaignId = env.campaign()
        val parent = env.quest(campaignId, "The Dinner Invitation")
        val child = env.quest(campaignId, "Find the Missing Coachman")

        assertEquals(
            AddRelationResult.Added,
            env.relations.addRelation(parent, child, QuestRelationType.PARENT_CHILD)
        )

        // The duplicate check runs ahead of the cycle check, so re-stating an existing parent link
        // comes back as the duplicate it is and not as a cycle - the two are different sentences
        // and the user who sees the wrong one learns nothing.
        assertEquals(
            AddRelationResult.AlreadyExists,
            env.relations.addRelation(parent, child, QuestRelationType.PARENT_CHILD)
        )

        assertEquals(
            listOf(Triple(parent, child, QuestRelationType.PARENT_CHILD)),
            storedRelations()
        )
    }
