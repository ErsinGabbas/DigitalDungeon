import org.robolectric.RobolectricTestRunner

/**
 * Scenarios 9 and 10: linking quests to each other, and refusing the links that would corrupt the
 * journal.
 *
 * Run against the real [QuestRelationRepositoryImpl] over a real in-memory database, because every
 * question here is about what the *table* ends up holding. The two things worth proving cannot be
 * proven against a fake:
 *
 * **Normalisation** is why duplicates are impossible rather than merely unlikely. `FOLLOWS(a, b)`
 * and `PRECEDES(b, a)` are one fact, and the symmetric types read the same either way round, so the
 * repository rewrites the pair before it looks for a duplicate. The assertions below therefore
 * never check only the result value: they check the row that landed, and they check that saying the
 * same thing the other way round lands nothing. A test that only asserted `Added` would pass
 * against code that stored both directions.
 *
 * **The cycle check** is a graph walk, not a chain walk, because a quest may honestly have two
 * parents - a side quest that belongs under two story arcs. So one test closes a loop through the
 * *second* of two parents, which a walk that followed only the first parent it found would let
 * through.
 *
 * Every refusal is asserted twice over: the value that came back, and the fact that the table is
 * exactly as it was. A refusal that returned the right value and still inserted would be the worst
 * of the possible bugs here, since the screen would show the user a rejection over a stored row.
 *
 * Cross-campaign refusal (`DifferentCampaigns`) belongs to the campaign-isolation scenario and is
 * asserted there, not here.
 */
@RunWith(RobolectricTestRunner::class)
class QuestRelationScenarioTest {

    private lateinit var env: QuestTestEnvironment

    @Before
    fun setUp() {
        env = QuestTestEnvironment()
    }

    @After
    fun tearDown() {
        env.close()
    }

    /**
     * Every row in the table as (source, target, type).
     *
     * Read straight from the DAO and not through [QuestRelationRepository.getRelationsForQuest],
     * because the refusal tests have to be able to say "nothing anywhere" rather than "nothing on
     * the quest I happened to ask about". The row id is dropped: what a relation joins is its whole
     * identity, and an autogenerated id would only make the expected values depend on how many rows
     * the test wrote before.
     */
    private suspend fun storedRelations(): List<Triple<Int, Int, QuestRelationType>> =
        env.database.questRelationDao().getAllRelations()
            .map { Triple(it.sourceQuestId, it.targetQuestId, it.relationType) }

    /** The same shape as [storedRelations], narrowed to what one quest can see from either end. */
    private suspend fun relationsFor(questId: Int): List<Triple<Int, Int, QuestRelationType>> =
        env.relations.getRelationsForQuest(questId).first()
            .map { Triple(it.sourceQuestId, it.targetQuestId, it.relationType) }

    private val noRelations = emptyList<Triple<Int, Int, QuestRelationType>>()

    // --------------------------------------------------- parent and child

    @Test
    fun addRelation_parentChild_storesTheParentAsSourceAndIsReadableFromBothEnds() = runTest {

        val campaignId = env.campaign()
        val parent = env.quest(campaignId, "The Dinner Invitation")
        val child = env.quest(campaignId, "Find the Missing Coachman")

        assertEquals(
            AddRelationResult.Added,
            env.relations.addRelation(parent, child, QuestRelationType.PARENT_CHILD)
        )

        // Which end is the parent is asserted explicitly, not inferred from the parameter names:
        // the repository's cycle walk reads `sourceQuestId` as the parent, and the screen draws the
        // source above the target. If that convention ever flipped, every ancestry answer would
        // invert while still returning `Added`.
        assertEquals(
            listOf(Triple(parent, child, QuestRelationType.PARENT_CHILD)),
            storedRelations()
        )

        // One row, visible from both quests. The child has to be able to name the arc it belongs
        // to without the parent being asked first, which is why the read covers both columns.
        assertEquals(relationsFor(parent), relationsFor(child))
        assertEquals(1, relationsFor(child).size)
    }

    @Test
    fun addRelation_severalChildrenUnderOneParent_areAllStored() = runTest {

        val campaignId = env.campaign()
        val arc = env.quest(campaignId, "The Dinner Invitation")
        val firstChild = env.quest(campaignId, "Find the Missing Coachman")
        val secondChild = env.quest(campaignId, "Survive the Banquet")
        val thirdChild = env.quest(campaignId, "Recover the Tarokka Deck")

        assertEquals(
            AddRelationResult.Added,
            env.relations.addRelation(arc, firstChild, QuestRelationType.PARENT_CHILD)
        )
        assertEquals(
            AddRelationResult.Added,
            env.relations.addRelation(arc, secondChild, QuestRelationType.PARENT_CHILD)
        )
        assertEquals(
            AddRelationResult.Added,
            env.relations.addRelation(arc, thirdChild, QuestRelationType.PARENT_CHILD)
        )

        assertEquals(
            listOf(
                Triple(arc, firstChild, QuestRelationType.PARENT_CHILD),
                Triple(arc, secondChild, QuestRelationType.PARENT_CHILD),
                Triple(arc, thirdChild, QuestRelationType.PARENT_CHILD)
            ),
            storedRelations()
        )

        // Each child sees only its own link; only the arc sees all three.
        assertEquals(3, relationsFor(arc).size)
        assertEquals(1, relationsFor(secondChild).size)
    }

    @Test
    fun addRelation_twoParentsOverOneChild_areBothStored() = runTest {

        val campaignId = env.campaign()
        val firstArc = env.quest(campaignId, "The Dinner Invitation")
        val secondArc = env.quest(campaignId, "The Hunt for Van Richten")
        val sideQuest = env.quest(campaignId, "Buy Silvered Weapons in Vallaki")

        assertEquals(
            AddRelationResult.Added,
            env.relations.addRelation(firstArc, sideQuest, QuestRelationType.PARENT_CHILD)
        )

        // Deliberate, and the reason the cycle check is a graph walk rather than a chain walk: one
        // errand can genuinely serve two story arcs, and forcing the DM to pick one would make the
        // journal less true than the table it is kept in.
        assertEquals(
            AddRelationResult.Added,
            env.relations.addRelation(secondArc, sideQuest, QuestRelationType.PARENT_CHILD)
        )

        assertEquals(
            listOf(
                Triple(firstArc, sideQuest, QuestRelationType.PARENT_CHILD),
                Triple(secondArc, sideQuest, QuestRelationType.PARENT_CHILD)
            ),
            storedRelations()
        )
        assertEquals(2, relationsFor(sideQuest).size)
    }

    @Test
    fun updateQuestStatus_onOneEndOfAParentChildLink_leavesTheOtherEndAlone() = runTest {

        val campaignId = env.campaign()
        val parent = env.quest(campaignId, "The Dinner Invitation")
        val child = env.quest(campaignId, "Find the Missing Coachman")
        env.relations.addRelation(parent, child, QuestRelationType.PARENT_CHILD)

        env.quests.updateQuestStatus(parent, QuestStatus.COMPLETED)

        // A child is not a sub-item. Nothing propagates along the link, in either direction, which
        // is what lets a parent arc be closed while an errand under it is still open.
        assertEquals(QuestStatus.COMPLETED, env.questById(parent)?.status)
        assertEquals(QuestStatus.NOT_STARTED, env.questById(child)?.status)

        env.quests.updateQuestStatus(child, QuestStatus.FAILED)

        assertEquals(QuestStatus.COMPLETED, env.questById(parent)?.status)
        assertEquals(QuestStatus.FAILED, env.questById(child)?.status)
    }

    @Test
    fun deleteRelation_onAParentChildLink_removesTheLinkAndNeitherQuest() = runTest {

        val campaignId = env.campaign()
        val parent = env.quest(campaignId, "The Dinner Invitation")
        val child = env.quest(campaignId, "Find the Missing Coachman")
        env.relations.addRelation(parent, child, QuestRelationType.PARENT_CHILD)

        val relationId = env.relations.getRelationsForQuest(parent).first().single().id
        env.relations.deleteRelation(relationId)

        assertEquals(noRelations, storedRelations())

        // The cascade on this table runs from quest to relation and never back. Unlinking two
        // quests is the cheap, reversible act the screen needs it to be; it is not a deletion.
        assertNotNull(env.questById(parent))
        assertNotNull(env.questById(child))

        // Sorted, because the quest list comes back in display order and this test has no opinion
        // about that - only about both quests still being in the campaign.
        assertEquals(
            listOf("Find the Missing Coachman", "The Dinner Invitation"),
            env.questTitlesIn(campaignId).sorted()
        )
    }

    // --------------------------------------------- the other relation types

    @Test
    fun addRelation_precedesAlternativeAndRelated_areEachStoredAsTheirOwnRow() = runTest {

        val campaignId = env.campaign()
        val first = env.quest(campaignId, "Escort the Wagon to Vallaki")
        val second = env.quest(campaignId, "Attend the Festival of the Blazing Sun")
        val third = env.quest(campaignId, "Bargain with the Vistani")
        val fourth = env.quest(campaignId, "Steal the Tome from Argynvostholt")

        assertEquals(
            AddRelationResult.Added,
            env.relations.addRelation(first, second, QuestRelationType.PRECEDES)
        )
        assertEquals(
            AddRelationResult.Added,
            env.relations.addRelation(second, third, QuestRelationType.ALTERNATIVE)
        )
        assertEquals(
            AddRelationResult.Added,
            env.relations.addRelation(third, fourth, QuestRelationType.RELATED)
        )

        // The type is stored as given for all three. Only `FOLLOWS` is rewritten into another type,
        // and that is asserted on its own below.
        assertEquals(
            listOf(
                Triple(first, second, QuestRelationType.PRECEDES),
                Triple(second, third, QuestRelationType.ALTERNATIVE),
                Triple(third, fourth, QuestRelationType.RELATED)
            ),
            storedRelations()
        )

        // The middle quest sits in two different kinds of link at once, and sees both.
        assertEquals(
            listOf(
                Triple(first, second, QuestRelationType.PRECEDES),
                Triple(second, third, QuestRelationType.ALTERNATIVE)
            ),
            relationsFor(second)
        )
    }

    @Test
    fun addRelation_twoPrecedesLinks_formAnOrderedChain() = runTest {

        val campaignId = env.campaign()
        val firstStep = env.quest(campaignId, "Find the Missing Coachman")
        val secondStep = env.quest(campaignId, "Escort the Wagon to Vallaki")
        val thirdStep = env.quest(campaignId, "Attend the Festival of the Blazing Sun")

        env.relations.addRelation(firstStep, secondStep, QuestRelationType.PRECEDES)
        env.relations.addRelation(secondStep, thirdStep, QuestRelationType.PRECEDES)

        // Direction is the whole content of a `PRECEDES` row, so the chain is only readable if the
        // middle step is a target in one row and a source in the other.
        assertEquals(
            listOf(
                Triple(firstStep, secondStep, QuestRelationType.PRECEDES),
                Triple(secondStep, thirdStep, QuestRelationType.PRECEDES)
            ),
            relationsFor(secondStep)
        )
        assertEquals(1, relationsFor(firstStep).size)
        assertEquals(1, relationsFor(thirdStep).size)
    }

    // ------------------------------------------------------- normalisation

    @Test
    fun addRelation_follows_isStoredAsPrecedesWithTheEndsSwapped() = runTest {

        val campaignId = env.campaign()
        val earlier = env.quest(campaignId, "Find the Missing Coachman")
        val later = env.quest(campaignId, "Escort the Wagon to Vallaki")

        // Said in the direction the DM is thinking in: the later quest follows the earlier one.
        assertEquals(
            AddRelationResult.Added,
            env.relations.addRelation(later, earlier, QuestRelationType.FOLLOWS)
        )

        // `FOLLOWS` never reaches the table. Asserting the rewritten row rather than just `Added`
        // is the point of the test: if it were stored as given, the same ordering could be
        // expressed twice and the two copies could later be edited apart.
        assertEquals(
            listOf(Triple(earlier, later, QuestRelationType.PRECEDES)),
            storedRelations()
        )
    }

    @Test
    fun addRelation_precedesThenTheSameOrderingAsFollows_isAlreadyExistsAndLeavesOneRow() =
        runTest {

            val campaignId = env.campaign()
            val earlier = env.quest(campaignId, "Find the Missing Coachman")
            val later = env.quest(campaignId, "Escort the Wagon to Vallaki")

            assertEquals(
                AddRelationResult.Added,
                env.relations.addRelation(earlier, later, QuestRelationType.PRECEDES)
            )

            // The same fact, phrased as its inverse. Normalisation happens before the duplicate
            // check, which is the only reason this is caught at all.
            assertEquals(
                AddRelationResult.AlreadyExists,
                env.relations.addRelation(later, earlier, QuestRelationType.FOLLOWS)
            )

            assertEquals(
                listOf(Triple(earlier, later, QuestRelationType.PRECEDES)),
                storedRelations()
            )
        }

    @Test
    fun addRelation_alternativeFromTheLargerId_isStoredWithTheSmallerIdFirst() = runTest {

        val campaignId = env.campaign()
        val smallerId = env.quest(campaignId, "Bargain with the Vistani")
        val largerId = env.quest(campaignId, "Fight Your Way Past the Vistani")

        // Asserted rather than assumed: the canonical form is defined by id order, so the test has
        // to know which of its two quests is which before it can claim anything about the row.
        assertTrue(smallerId < largerId)

        assertEquals(
            AddRelationResult.Added,
            env.relations.addRelation(largerId, smallerId, QuestRelationType.ALTERNATIVE)
        )

        // A symmetric relation says the same thing read either way, so it is stored one way only.
        assertEquals(
            listOf(Triple(smallerId, largerId, QuestRelationType.ALTERNATIVE)),
            storedRelations()
        )
    }

    @Test
    fun addRelation_alternativeBothWaysRound_isAddedThenAlreadyExistsWithOneRow() = runTest {

        val campaignId = env.campaign()
        val oneWay = env.quest(campaignId, "Bargain with the Vistani")
        val otherWay = env.quest(campaignId, "Fight Your Way Past the Vistani")

        assertEquals(
